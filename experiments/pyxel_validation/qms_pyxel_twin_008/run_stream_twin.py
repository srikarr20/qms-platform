from pathlib import Path
import json
import shutil

import numpy as np
from astropy.io import fits
from scipy.constants import k, m_e
from scipy.interpolate import PchipInterpolator
from scipy.optimize import minimize_scalar

from pyxel.models.charge_transfer.utils_cdm import run_cdm_parallel


ROOT = Path(__file__).resolve().parent.parent

SOURCE = ROOT / "qms_pyxel_twin_003" / "results"
STREAM = ROOT / "qms_pyxel_twin_008" / "stream"
STATE_DIR = ROOT / "qms_pyxel_twin_008" / "state"

BASELINE_ROOT = (
    ROOT
    / "qms_pyxel_001"
    / "cti_observable_results"
    / "cti_000"
)

CAL_FILE = (
    ROOT
    / "qms_pyxel_twin_004"
    / "qms_pyxel_twin_004_noise_calibration.json"
)

CTI_THRESHOLD = 0.20
NOISE_THRESHOLD = 0.10


def latest(root, filename):
    files = sorted(root.rglob(filename))
    if not files:
        raise FileNotFoundError(f"{filename} missing under {root}")
    return files[-1]


def load_pixel(root):
    return np.asarray(
        np.load(latest(root, "detector_pixel.npy")),
        dtype=np.float64,
    )


def load_image(root):
    return np.asarray(
        fits.getdata(latest(root, "detector_image.fits")),
        dtype=np.float64,
    )


def rmse(a, b):
    return float(np.sqrt(np.mean((a - b) ** 2)))


baseline_pixel = load_pixel(BASELINE_ROOT)


# -----------------------------
# CTI model
# -----------------------------

beta = 0.3
vg = 1.62e-10
transfer_period = 9.4722e-04
fwc = 100000.0
temperature = 300.0

effective_mass = 0.5 * m_e

vth = 100.0 * np.sqrt(
    3.0 * k * temperature / effective_mass
)

tr = np.array([3.e-2], dtype=float)
sigma_capture = np.array([1.e-10], dtype=float)


def simulate_cti(log10_density):
    density = 10.0 ** log10_density

    arr = baseline_pixel.copy()

    return run_cdm_parallel(
        array=arr,
        beta=beta,
        vg=vg,
        t=transfer_period,
        fwc=fwc,
        vth=vth,
        tr=tr,
        nt=np.array([density], dtype=float),
        sigma=sigma_capture,
        charge_injection=False,
        chg_inj_parallel_transfers=baseline_pixel.shape[0],
    )


def estimate_cti(observed_pixel):

    def objective(log10_density):
        pred = simulate_cti(log10_density)
        return rmse(pred, observed_pixel)

    result = minimize_scalar(
        objective,
        bounds=(7.0, 11.5),
        method="bounded",
        options={"xatol": 1e-8},
    )

    return (
        10.0 ** result.x,
        result.fun,
    )


# -----------------------------
# Noise inverse calibration
# -----------------------------

cal = json.loads(CAL_FILE.read_text())

std_support = np.asarray(
    cal["inverse_support"]["residual_std"],
    dtype=float
)

sigma_support = np.asarray(
    cal["inverse_support"]["sigma"],
    dtype=float
)

noise_inverse = PchipInterpolator(
    std_support,
    sigma_support,
    extrapolate=True,
)


def estimate_noise(observed_image, clean_reference):
    residual = observed_image - clean_reference
    residual_std = float(residual.std())

    sigma = float(
        noise_inverse(residual_std)
    )

    return max(sigma, 0.0), residual_std


# -----------------------------
# Persistent twin state
# -----------------------------

state_file = STATE_DIR / "twin_state.json"

if state_file.exists():
    twin_state = json.loads(
        state_file.read_text()
    )
else:
    twin_state = {
        "history": []
    }


def predict(history):

    if len(history) < 2:
        return None

    a = history[-2]
    b = history[-1]

    return {
        "cti":
            b["cti"]
            + (b["cti"] - a["cti"]),

        "noise":
            b["noise"]
            + (b["noise"] - a["noise"]),
    }


# -----------------------------
# Simulated live stream
# -----------------------------

source_states = sorted(
    p for p in SOURCE.iterdir()
    if p.is_dir()
)

print()
print("=== QMS-PYXEL-TWIN-008 STREAMING TWIN ===")
print()


for source in source_states:

    name = source.name

    # Simulate arrival of a new detector state.
    stream_item = STREAM / name

    if not stream_item.exists():
        shutil.copytree(
            source,
            stream_item
        )

    observed_pixel = load_pixel(stream_item)
    observed_image = load_image(stream_item)

    # Current detector inference.
    cti_hat, pixel_fit_residual = estimate_cti(
        observed_pixel
    )

    # For this first streaming version,
    # use the corresponding CTI-only prediction
    # previously generated by TWIN-003.
    cti_prediction_root = (
        ROOT
        / "qms_pyxel_twin_003"
        / "prediction_results"
        / name
    )

    cti_only_image = load_image(
        cti_prediction_root
    )

    noise_hat, image_residual_std = estimate_noise(
        observed_image,
        cti_only_image
    )

    current = {
        "cti": float(cti_hat),
        "noise": float(noise_hat),
    }

    pred = predict(
        twin_state["history"]
    )

    if pred is None:

        mode = "INITIALIZE"
        trigger = True
        cti_innovation = None
        noise_innovation = None

    else:

        cti_innovation = abs(
            pred["cti"] - current["cti"]
        ) / current["cti"]

        noise_innovation = abs(
            pred["noise"] - current["noise"]
        ) / current["noise"]

        trigger = (
            cti_innovation > CTI_THRESHOLD
            or
            noise_innovation > NOISE_THRESHOLD
        )

        mode = (
            "REESTIMATE_AND_ADAPT"
            if trigger
            else
            "ASSIMILATE"
        )

    event = {
        "time": name,

        "predicted":
            pred,

        "cti":
            current["cti"],

        "noise":
            current["noise"],

        "pixel_fit_residual":
            float(pixel_fit_residual),

        "image_residual_std":
            float(image_residual_std),

        "cti_innovation_relative":
            cti_innovation,

        "noise_innovation_relative":
            noise_innovation,

        "trigger_reestimate":
            bool(trigger),

        "mode":
            mode,
    }

    twin_state["history"].append(
        event
    )

    state_file.write_text(
        json.dumps(
            twin_state,
            indent=2
        ) + "\n"
    )

    print(name)

    if pred is not None:
        print(
            " predicted:",
            f"CTI={pred['cti']:.6e}",
            f"noise={pred['noise']:.6e}"
        )

    print(
        " inferred :",
        f"CTI={current['cti']:.6e}",
        f"noise={current['noise']:.6e}"
    )

    print(
        " action:",
        mode
    )

    print()


print("=" * 60)
print("STREAM COMPLETE")
print("=" * 60)

print()
print(
    "States consumed:",
    len(twin_state["history"])
)

print(
    "Persistent state:",
    state_file
)
